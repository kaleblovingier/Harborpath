// SAMHSA FindTreatment.gov service taxonomy -> data/service-codes.json
//
// The feed also carries SAMHSA's official Spanish names. They are kept as `es`
// on each category and service, and written to public/js/locales/es-services.js
// (code -> Spanish name) so the web app can show facility details in Spanish.
// The client only downloads that file when Spanish is active.
import { writeFile } from 'node:fs/promises';
import { download } from '../lib/fetch.mjs';

const url = 'https://findtreatment.gov/locator/serviceCategories.json';
export const SPANISH_NAMES_FILE = new URL('../../public/js/locales/es-services.js', import.meta.url);

// The feed contains a few mis-encoded registered-trademark characters.
const tidy = (s) => String(s ?? '').replace(/�|®/g, '').replace(/\s+/g, ' ').trim();

// Obvious typos in the Spanish feed, fixed so the app does not repeat them.
const SPANISH_FIXES = [
  [/\bo o\b/g, 'o'], // "sordos o o con problemas de audición"
  [/\bHIS\//g, 'IHS/'], // "Fondos de HIS/Tribales/Urbanos" (Indian Health Service)
];

function tidySpanish(s) {
  let out = tidy(s);
  for (const [re, to] of SPANISH_FIXES) out = out.replace(re, to);
  return out;
}

// Category names sometimes end in examples, e.g. "(p. ej., ambulatorio, ...)".
const stripExamples = (s) => s.replace(/\s*\(p\. ej\.[^)]*\)/g, '').trim();

export function compactCategories(feed) {
  return feed.map((c) => ({
    code: c.categoryCode.trim(),
    name: c.categoryName.trim(),
    es: stripExamples(tidySpanish(c.spanishCategoryName)) || c.categoryName.trim(),
    sa: c.saCategory === 'Y',
    mh: c.mhCategory === 'Y',
    services: c.serviceCodeList.map((s) => ({
      code: s.serviceCode.trim(),
      name: tidy(s.serviceName),
      es: tidySpanish(s.serviceSpanishName) || tidy(s.serviceName),
      sa: s.saCode === 'Y',
      mh: s.mhCode === 'Y',
    })),
  }));
}

/** Source of public/js/locales/es-services.js for the given categories. */
export function spanishNamesModule(categories) {
  const names = { categories: {}, services: {} };
  for (const c of categories) {
    names.categories[c.code] = c.es;
    // Insertion order follows SAMHSA's display order.
    names.services[c.code] = Object.fromEntries(c.services.map((s) => [s.code, s.es]));
  }
  return [
    '// Generated by scripts/sources/service-codes.mjs from SAMHSA\'s official Spanish',
    '// service names (findtreatment.gov/locator/serviceCategories.json). Do not edit:',
    '// run `npm run data:build -- --only serviceCodes` instead.',
    `export default ${JSON.stringify(names)};`,
    '',
  ].join('\n');
}

export default {
  id: 'serviceCodes',
  file: 'service-codes.json',
  async build() {
    const { buf } = await download(url);
    const categories = compactCategories(JSON.parse(buf.toString('utf8')));
    await writeFile(SPANISH_NAMES_FILE, spanishNamesModule(categories));
    return { data: { categories }, meta: { url, categories: categories.length } };
  },
};
